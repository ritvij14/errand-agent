import { openDatabase, runMigrations } from "../shared/db.js";
import { seedDemoUsers } from "../auth/index.js";
import { runScenario, checkInvariants, coverageReport, type EvalScenario, describeSteps } from "./runner.js";
import { SCENARIOS } from "./scenarios.js";
import { DEMO_USERS } from "../shared/demo-users.js";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { mkdir, unlink } from "node:fs/promises";
import { join } from "node:path";

// The eval CLI (MH-8, deliverable 3): runs every accepted scenario, prints the table
// and writes docs/evals/eval-table.md. Exits non-zero if any scenario fails, so the
// root `npm test` (vitest → evals) fails on either stage.

const here = fileURLToPath(new URL("../..", import.meta.url)); // server/
const repoRoot = join(here, "..");
const evalTablePath = join(repoRoot, "docs/evals/eval-table.md");
const evalDataDir = join(here, "data"); // server/data

const commitOf = (): string => {
  try {
    return execSync(`git rev-parse --short HEAD`, { cwd: repoRoot }).toString().trim();
  } catch {
    return "(no git)";
  }
};

export const runAllEvals = async (): Promise<{ failed: number; total: number; rows: string[] }> => {
  const rows: string[] = [
    "| id | scenario | expected | actual | pass | notes |",
    "| --- | --- | --- | --- | --- | --- |",
  ];
  let failed = 0;
  let total = 0;
  for (const scenario of Object.values(SCENARIOS) as EvalScenario[]) {
    total += 1;
    // fresh database per scenario (§ 2.5.10), in server/data (git-ignored)
    const dbPath = join(evalDataDir, `eval-${scenario.id}.db`);
    const db = openDatabase(dbPath);
    runMigrations(db, join(here, "migrations"));
    seedDemoUsers(db, Date.now());
    const result = await runScenario(db, scenario, DEMO_USERS[0]!.id);
    const invariants = checkInvariants(db, { modelCalls: 6, toolCalls: 10, elapsedMs: 60_000 });
    result.firstFailure ??= invariants;
    const pass = !!result.firstFailure ? false : result.pass;
    await unlink(dbPath).catch(() => undefined);
    rows.push(
      `| ${scenario.id} | ${scenario.name} | ${describeSteps(scenario.steps).replace(/\|/g, "\\|")} | ${result.actual.replace(/\|/g, "\\|")} | ${pass ? "✅" : "❌"} | ${(result.notes ?? "").replace(/\|/g, "\\|")} |`,
    );
    if (!pass) failed += 1;
  }
  return { failed, total, rows };
};

const main = async (): Promise<void> => {
  const started = new Date().toISOString();
  const missingCoverage = coverageReport(Object.keys(SCENARIOS));
  const { failed, total, rows } = await runAllEvals();
  await mkdir(join(repoRoot, "docs/evals"), { recursive: true });
  const header = [
    "# Eval table (generated by `npm run evals` — never edited by hand)",
    "",
    `- Run: ${started}`,
    `- Commit: ${commitOf()}`,
    `- Seed: every scenario's documented fixed seed (defaults in scenarios.ts)`,
    "",
  ];
  const coverageRow = missingCoverage.length
    ? [
        `| coverage | the brief's 8 must-cover categories all have a scenario | missing: ${missingCoverage.join(", ")} | ❌ | coverage check (U36) |`,
      ]
    : [];
  await (
    await import("node:fs/promises")
  ).writeFile(evalTablePath, [...header, ...rows, ...coverageRow, ""].join("\n"));
  console.log(`\nEvals: ${total - failed}/${total} passed. Table written to docs/evals/eval-table.md`);
  if (missingCoverage.length > 0) {
    console.error(`coverage FAILED: missing ${missingCoverage.join(", ")}`);
    process.exitCode = 1;
  }
  if (failed > 0) {
    console.error(`${failed} eval(s) FAILED`);
    process.exitCode = 1;
  }
};

const invokedDirectly = process.argv[1]?.endsWith("eval.cli.ts") || process.argv[1]?.endsWith("eval");
if (invokedDirectly) {
  await main();
}
